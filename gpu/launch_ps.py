"""Run point 80000 and publish the validated production power spectrum."""
from time import perf_counter
START = perf_counter()

import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import tempfile


def package_key(stage, root):
    seed = hashlib.sha256()
    seed.update(repr((sys.version, sys.executable, platform.machine(), str(root))).encode())
    upstream = root / "resident_filter_20261118/fix/package/py21cmfast"
    inputs = [f for f in stage.iterdir() if f.suffix in {".py", ".h", ".cu"}]
    inputs.extend(f for f in upstream.rglob("*") if f.is_file() and f.suffix in {".py", ".h", ".c"})
    for f in sorted(inputs):
        seed.update(str(f).encode())
        seed.update(f.read_bytes())
    for directory in (root / "include", root / "lib"):
        for f in sorted(directory.iterdir()):
            stat = f.stat()
            seed.update(repr((f.name, stat.st_size, stat.st_mtime_ns)).encode())
    return seed.hexdigest()[:24]


def get_package(stage, root, cache, env):
    key = package_key(stage, root)
    revision = cache / "native" / key
    revision.parent.mkdir(parents=True, exist_ok=True)
    with (revision.parent / f"{key}.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        package = revision / "package"
        if package.is_dir():
            return package, True
        staging = Path(tempfile.mkdtemp(prefix=f".{key}-", dir=revision.parent))
        try:
            with (staging / "build.log").open("w") as log:
                try:
                    subprocess.run([sys.executable, str(stage / "build.py"), str(root), str(staging)],
                                   env=env, stdout=log, stderr=subprocess.STDOUT, check=True)
                except subprocess.CalledProcessError:
                    print((staging / "build.log").read_text()[-6000:], file=sys.stderr)
                    raise
            os.rename(staging, revision)
        finally:
            if staging.exists():
                shutil.rmtree(staging)
    return package, False


def sync_directory(path):
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def write_synced_json(path, report):
    with path.open("w") as f:
        json.dump(report, f, indent=2, allow_nan=False)
        f.write("\n")
        f.flush()
        os.fsync(f.fileno())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    inputs = parser.add_mutually_exclusive_group(required=True)
    inputs.add_argument("--cpu-ic", type=Path)
    inputs.add_argument("--seed", action="store_true", help="Use point 80000's production GSL seed")
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--baseline", action="store_true", help="Use the previous production PS benchmark configuration")
    parser.add_argument("--full-coeval", action="store_true")
    parser.add_argument("--compression", choices=("none","lzf"), default="none")
    parser.add_argument("--include-ic", action="store_true", help="Bundle the complete native IC file")
    parser.add_argument("--gpu-full-ic", action="store_true",
                        help="Write a complete low-resolution-mode native IC generated by GPU")
    parser.add_argument("--reload-gpu-ic", action="store_true",
                        help="Replay a GPU-generated IC file with the seed profile")
    parser.add_argument("--overlap-ic-write", action="store_true",
                        help="Write the GPU-generated IC while coeval evolves")
    parser.add_argument("--sparse-ic-zeros", action="store_true",
                        help="Use HDF5 zero-filled storage for unused high-resolution IC fields")
    parser.add_argument("--coeval-lzf-workers", type=int, default=1,
                        help="Encode coeval HDF5 chunks with this many host workers")
    parser.add_argument("--paired-archive", action="store_true")
    args = parser.parse_args()
    if args.paired_archive and (
        not args.gpu_full_ic or not args.full_coeval or args.compression != "lzf"
        or args.coeval_lzf_workers < 2 or args.overlap_ic_write or args.sparse_ic_zeros
    ):
        parser.error("Paired archive requires complete GPU IC and parallel coeval LZF")
    if args.coeval_lzf_workers < 1:
        parser.error("--coeval-lzf-workers must be at least one")
    if args.coeval_lzf_workers > 1 and (not args.full_coeval or args.compression != "lzf"):
        parser.error("Parallel encoding requires --full-coeval --compression lzf")
    if args.sparse_ic_zeros and not args.gpu_full_ic:
        parser.error("--sparse-ic-zeros requires --gpu-full-ic")
    if args.overlap_ic_write and not args.gpu_full_ic:
        parser.error("--overlap-ic-write requires --gpu-full-ic")
    if args.reload_gpu_ic and (not args.cpu_ic or args.baseline):
        parser.error("--reload-gpu-ic requires --cpu-ic with the optimized profile")
    if args.gpu_full_ic and not (args.include_ic and args.seed and not args.baseline):
        parser.error("--gpu-full-ic requires --seed --include-ic with the optimized profile")
    if args.include_ic and not args.full_coeval:
        parser.error("--include-ic requires --full-coeval")
    stage = Path(__file__).resolve().parent
    root = stage.parent
    output, cache = args.output.resolve(), args.cache.resolve()
    if args.cpu_ic and not args.cpu_ic.is_file():
        parser.error(f"IC file does not exist: {args.cpu_ic}")
    output.parent.mkdir(parents=True, exist_ok=True)
    with (output.parent / f".{output.name}.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if output.exists():
            parser.error(f"Output already exists: {output}")
        env = dict(os.environ)
        env.update(PS_GPU_ROOT=str(root), LD_LIBRARY_PATH=str(root / "lib"),
                   XDG_CONFIG_HOME=str(cache / "config"), CUPY_CACHE_DIR=str(cache / "cupy"),
                   PYTHONUNBUFFERED="1", OPENBLAS_NUM_THREADS="1", MKL_NUM_THREADS="1",
                   NUMEXPR_NUM_THREADS="1", PS_XRAY_NATIVE_MODE="4",
                   PS_NATIVE_CONDITIONAL="0", PS_NATIVE_SIGMA="1", PS_NATIVE_XRAY="0",
                   PS_NATIVE_MHR="1", PS_NATIVE_COLLAPSE="1", PS_COMPARE_VOXELS="0",
                   PS_FFTW_PERTURB_DENSITY="1" if args.baseline else "0",
                   PS_CONDITIONAL_MODE="0" if args.baseline else "3",
                   PS_BATCH_FILTER="0" if args.baseline else "1", PS_PRODUCTION_PS_ONLY="1")
        profile = env.get("PS_SEED_PROFILE","fftw-both")
        if (args.seed or args.reload_gpu_ic) and not args.baseline:
            if profile not in {"fftw-both","fftw-heat","fftw-ion","fftw-native"}:
                parser.error("Invalid PS_SEED_PROFILE")
            env["PS_FFTW_PERTURB_DENSITY"]="1"
            env["PS_CONDITIONAL_MODE"]={"fftw-both":"3","fftw-heat":"2","fftw-ion":"1","fftw-native":"0"}[profile]
            env["PS_GSL_EXACT_POWER"]="1"
        env["PS_LAZY_COEVAL_IC"] = env.get(
            "PS_LAZY_COEVAL_IC", "1" if args.cpu_ic and not args.baseline else "0"
        )
        env["OMP_NUM_THREADS"] = env.get("SLURM_CPUS_PER_TASK", "8")
        env["PS_FULL_COEVAL"] = "1" if args.full_coeval else "0"
        env["PS_COEVAL_COMPRESSION"] = args.compression
        env["PS_COEVAL_LZF_WORKERS"] = str(args.coeval_lzf_workers)
        env["PS_GENERATE_FULL_IC"] = "1" if args.include_ic and args.seed and not args.gpu_full_ic else "0"
        env["PS_PAIRED_ARCHIVE"] = "1" if args.paired_archive else "0"
        env["PS_ARCHIVE_GPU_IC"] = "1" if args.gpu_full_ic else "0"
        env["PS_OVERLAP_IC_WRITE"] = "1" if args.overlap_ic_write else "0"
        env["PS_SPARSE_IC_ZEROS"] = "1" if args.sparse_ic_zeros else "0"
        if args.cpu_ic:
            env["PS_KEEP_CPU_IC"] = "1"
        env.pop("PS_IC_FFT64", None)
        env.pop("PS_GPU_SCALE_TRACE_FILE", None)
        cache.mkdir(parents=True, exist_ok=True)
        existing_kernels = any((cache / "cupy").glob("*.cubin"))
        begin = perf_counter()
        package, build_hit = get_package(stage, root, cache, env)
        package_seconds = perf_counter() - begin
        env["PYTHONPATH"] = str(package)
        staging = Path(tempfile.mkdtemp(prefix=f".{output.name}-", dir=output.parent))
        try:
            with tempfile.TemporaryDirectory(prefix="ps-coeval-") as scratch:
                mode = ["--cpu-ic", str(args.cpu_ic.resolve())] if args.cpu_ic else ["--gsl-modes"]
                begin = perf_counter()
                subprocess.run([sys.executable, str(stage / "run_point.py"), "gpu-timing",
                                str(staging), scratch, *mode], env=env, check=True)
                worker_seconds = perf_counter() - begin
            report = json.loads((staging / "gpu-timing.json").read_text())
            if report["production_reference"]["ps_full"]["failed"]:
                if env.get("PS_ALLOW_FAILED_BENCHMARK") == "1":
                    write_synced_json(output.parent/f"{output.name}-rejected.json",
                                      {"profile":profile,"report":report,"worker_seconds":worker_seconds})
                raise RuntimeError(f"Production 32-bin PS did not pass: {report['production_reference']['ps_full']}")
            if not (staging / "gpu-timing-outputs.npz").is_file():
                raise RuntimeError("Simulation did not produce spectra")
            ic_copy_seconds=0.
            if args.include_ic and args.cpu_ic:
                begin=perf_counter()
                shutil.copyfile(args.cpu_ic,staging/"initial-conditions.h5")
                ic_copy_seconds=perf_counter()-begin
            if args.full_coeval and not (staging/"coeval-fields.h5").is_file():
                raise RuntimeError("Missing full coeval archive")
            if args.include_ic and not (staging/"initial-conditions.h5").is_file():
                raise RuntimeError("Missing full initial conditions")
            payload={f.name:f.stat().st_size for f in staging.iterdir() if f.is_file()}
            begin = perf_counter()
            for f in staging.iterdir():
                if f.is_file():
                    with f.open("rb") as stream:
                        os.fsync(stream.fileno())
            results_sync_seconds = perf_counter() - begin
            write_synced_json(staging / "launch-timing.json", {
                "native_package_cache_hit": build_hit,
                "existing_cuda_kernel_cache": existing_kernels,
                "native_package_setup_seconds": package_seconds,
                "worker_process_seconds": worker_seconds,
                "output_fsync_seconds": results_sync_seconds,
                "seconds_from_launcher_to_synced_results": perf_counter() - START,
                "input": "cpu_ic" if args.cpu_ic else "gsl_seed",
                "baseline": args.baseline,
                "payload_bytes":payload,
                "full_coeval":args.full_coeval,
                "coeval_lzf_workers": args.coeval_lzf_workers,
                "ic_copy_seconds":ic_copy_seconds,
                "included_complete_ic":args.include_ic,
                "gpu_full_ic": args.gpu_full_ic,
                "overlap_ic_write": args.overlap_ic_write,
                "sparse_ic_zeros": args.sparse_ic_zeros,
                "lazy_coeval_ic": env["PS_LAZY_COEVAL_IC"] == "1",
                "seed_profile": profile if (args.seed or args.reload_gpu_ic) and not args.baseline else None,
            })
            sync_directory(staging)
            os.rename(staging, output)
            sync_directory(output.parent)
            print(f"Published {output} in {perf_counter()-START:.3f} s", flush=True)
        finally:
            if staging.exists():
                shutil.rmtree(staging)


if __name__ == "__main__":
    main()
